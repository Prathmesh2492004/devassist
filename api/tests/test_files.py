from pathlib import Path

import pytest

from app.ingest.files import TooManyFilesError, iter_source_files


def _write(root: Path, rel: str, content: str | bytes) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, bytes):
        path.write_bytes(content)
    else:
        path.write_text(content, encoding="utf-8")


def _paths(root: Path, **limits: int) -> list[str]:
    limits = {"max_file_bytes": 300_000, "max_files": 1000, **limits}
    return [f.path for f in iter_source_files(root, **limits)]


def test_keeps_source_files_and_detects_language(tmp_path: Path) -> None:
    _write(tmp_path, "src/app.py", "print('hi')\n")
    _write(tmp_path, "web/page.tsx", "export const A = 1\n")
    _write(tmp_path, "Dockerfile", "FROM python:3.12\n")
    _write(tmp_path, ".github/workflows/ci.yml", "on: push\n")

    files = {
        f.path: f.language for f in iter_source_files(tmp_path, max_file_bytes=1000, max_files=10)
    }

    assert files == {
        ".github/workflows/ci.yml": "yaml",
        "Dockerfile": "dockerfile",
        "src/app.py": "python",
        "web/page.tsx": "tsx",
    }


def test_skips_dependencies_build_output_and_hidden_dirs(tmp_path: Path) -> None:
    _write(tmp_path, "node_modules/react/index.js", "x\n")
    _write(tmp_path, ".venv/lib/site.py", "x\n")
    _write(tmp_path, "dist/bundle.js", "x\n")
    _write(tmp_path, ".idea/workspace.xml", "x\n")
    _write(tmp_path, "src/keep.py", "x = 1\n")

    assert _paths(tmp_path) == ["src/keep.py"]


def test_skips_lockfiles_minified_binary_and_unknown_types(tmp_path: Path) -> None:
    _write(tmp_path, "package-lock.json", "{}\n")
    _write(tmp_path, "app.min.js", "var a=1;\n")
    _write(tmp_path, "logo.png", b"\x89PNG\r\n\x1a\n\x00\x00")
    _write(tmp_path, "data.bin.py", b"x = 1\x00\x00\x00")
    _write(tmp_path, "notes.xyz", "hello\n")
    _write(tmp_path, "main.py", "x = 1\n")

    assert _paths(tmp_path) == ["main.py"]


def test_skips_generated_and_minified_looking_files(tmp_path: Path) -> None:
    _write(tmp_path, "schema_pb.py", "# Code generated by protoc. DO NOT EDIT.\nx = 1\n")
    _write(tmp_path, "one_line.js", "var a=" + "1+" * 2000 + "1;\n")
    _write(tmp_path, "main.py", "x = 1\n")

    assert _paths(tmp_path) == ["main.py"]


def test_skips_files_over_the_size_limit(tmp_path: Path) -> None:
    _write(tmp_path, "big.py", "x = 1\n" * 1000)
    _write(tmp_path, "small.py", "x = 1\n")

    assert _paths(tmp_path, max_file_bytes=1000) == ["small.py"]


def test_never_follows_symlinks(tmp_path: Path) -> None:
    outside = tmp_path / "outside"
    _write(outside, "secret.py", "PASSWORD = 'x'\n")
    repo = tmp_path / "repo"
    _write(repo, "main.py", "x = 1\n")
    try:
        (repo / "link.py").symlink_to(outside / "secret.py")
        (repo / "linkdir").symlink_to(outside, target_is_directory=True)
    except OSError:
        pytest.skip("Creating symlinks needs extra permissions on this OS")

    assert _paths(repo) == ["main.py"]


def test_raises_when_repo_has_too_many_files(tmp_path: Path) -> None:
    for i in range(4):
        _write(tmp_path, f"f{i}.py", "x = 1\n")

    with pytest.raises(TooManyFilesError):
        _paths(tmp_path, max_files=3)
