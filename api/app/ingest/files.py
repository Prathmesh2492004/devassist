"""Decide which files in a cloned repository are worth indexing."""

import os
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path, PurePath

# Dependencies, build output and tool caches: large, not written by the repo's authors.
SKIP_DIRS = frozenset(
    {
        ".git", ".hg", ".svn", "node_modules", "bower_components", "vendor", "third_party",
        "dist", "build", "out", "target", "bin", "obj", ".next", ".nuxt", ".svelte-kit",
        "coverage", ".venv", "venv", "env", "__pycache__", ".mypy_cache", ".pytest_cache",
        ".ruff_cache", ".tox", ".gradle", ".idea", ".vscode", ".terraform", "site-packages",
    }
)  # fmt: skip

SKIP_FILES = frozenset(
    {
        "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "uv.lock",
        "Pipfile.lock", "Cargo.lock", "go.sum", "composer.lock", "Gemfile.lock",
    }
)  # fmt: skip

SKIP_SUFFIXES = (".min.js", ".min.css", ".map", ".snap", ".pb.go", "_pb2.py")

LANGUAGE_BY_EXTENSION = {
    ".py": "python", ".pyi": "python",
    ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".ts": "typescript", ".mts": "typescript", ".cts": "typescript", ".tsx": "tsx",
    ".java": "java",
    ".go": "go", ".rs": "rust", ".rb": "ruby", ".php": "php", ".cs": "csharp",
    ".c": "c", ".h": "c", ".cc": "cpp", ".cpp": "cpp", ".hpp": "cpp",
    ".kt": "kotlin", ".swift": "swift", ".scala": "scala",
    ".sql": "sql", ".sh": "shell", ".bash": "shell",
    ".md": "markdown", ".rst": "markdown",
    ".yaml": "yaml", ".yml": "yaml", ".toml": "toml", ".json": "json",
    ".html": "html", ".css": "css", ".scss": "css", ".vue": "vue", ".svelte": "svelte",
}  # fmt: skip

LANGUAGE_BY_FILENAME = {"Dockerfile": "dockerfile", "Makefile": "makefile"}

GENERATED_MARKERS = ("@generated", "do not edit", "auto-generated", "autogenerated")
MAX_JSON_BYTES = 50_000  # big JSON files are almost always data, not code
MAX_AVERAGE_LINE_LENGTH = 300  # higher than this means minified or machine-written


@dataclass(frozen=True)
class SourceFile:
    path: str  # relative to the repo root, always with forward slashes
    language: str
    text: str


class TooManyFilesError(Exception):
    pass


def detect_language(path: PurePath) -> str | None:
    return LANGUAGE_BY_FILENAME.get(path.name) or LANGUAGE_BY_EXTENSION.get(path.suffix.lower())


def iter_source_files(root: Path, *, max_file_bytes: int, max_files: int) -> Iterator[SourceFile]:
    """Yield every indexable file under root, in a stable order.

    Raises TooManyFilesError once more than max_files would be yielded.
    """
    count = 0
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        # Prune in place so os.walk never descends into skipped directories.
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and _is_visible_dir(d))
        for name in sorted(filenames):
            file = _read_if_indexable(Path(dirpath) / name, max_file_bytes)
            if file is None:
                continue
            language, text = file
            count += 1
            if count > max_files:
                raise TooManyFilesError(f"Repository has more than {max_files} indexable files")
            rel = (Path(dirpath) / name).relative_to(root).as_posix()
            yield SourceFile(path=rel, language=language, text=text)


def _is_visible_dir(name: str) -> bool:
    # Hidden directories are tool state, except .github, which holds CI workflows worth searching.
    return not name.startswith(".") or name == ".github"


def _read_if_indexable(path: Path, max_file_bytes: int) -> tuple[str, str] | None:
    name = path.name
    if name in SKIP_FILES or name.endswith(SKIP_SUFFIXES):
        return None
    # A symlink could point outside the clone (e.g. to /etc/passwd); never follow one.
    if path.is_symlink() or not path.is_file():
        return None
    language = detect_language(path)
    if language is None:
        return None

    size = path.stat().st_size
    if size == 0 or size > max_file_bytes or (language == "json" and size > MAX_JSON_BYTES):
        return None

    raw = path.read_bytes()
    if b"\0" in raw[:8192]:
        return None  # binary
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return None

    head = text[:1000].lower()
    if any(marker in head for marker in GENERATED_MARKERS):
        return None
    lines = text.count("\n") + 1
    if len(text) / lines > MAX_AVERAGE_LINE_LENGTH:
        return None
    return language, text
